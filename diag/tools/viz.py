# -*- coding: utf-8 -*-
"""Programmatic SVG stimulus builders for the APES diagnostic.

Every figure in the question bank is generated by one of these functions, so
axis scaling, tick labels and plotted points are computed from the same data
the question text and answer key are derived from. Nothing is hand-typed.

All builders return a single-line SVG string using single-quoted attributes,
so the result can be embedded in a double-quoted JS/JSON string safely.
"""

FONT = "font-family='Helvetica, Arial, sans-serif'"
INK = "#222222"
GRID = "#E2E2E2"
SERIES_COLORS = ["#C41230", "#1565C0", "#2E7D32", "#6A1B9A", "#E65100", "#00695C"]


def _esc(s):
    return (str(s).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
            .replace("'", "&#39;").replace('"', "&quot;"))


def _n(v):
    """Format a number compactly: 3.0 -> '3', 3.25 -> '3.25'."""
    if isinstance(v, float) and abs(v - round(v)) < 1e-9:
        v = int(round(v))
    return str(v)


def _nice_ticks(lo, hi, count=5):
    """Return `count`+1 evenly spaced tick values spanning lo..hi."""
    step = (hi - lo) / float(count)
    return [lo + step * i for i in range(count + 1)]


# ──────────────────────────────────────────────────────────────────────────
# Caption wrapper
# ──────────────────────────────────────────────────────────────────────────
def _frame(w, h, body, caption=None):
    cap = ""
    ch = 0
    if caption:
        lines = _wrap(caption, 78)
        ch = 14 * len(lines) + 6
        cap = "".join(
            "<text x='%d' y='%d' font-size='11' fill='#555' text-anchor='middle'>%s</text>"
            % (w // 2, h + 14 + 14 * i, _esc(ln)) for i, ln in enumerate(lines))
    return ("<svg viewBox='0 0 %d %d' xmlns='http://www.w3.org/2000/svg' %s "
            "role='img' style='max-width:100%%;height:auto'>"
            "<rect width='%d' height='%d' fill='#FFFFFF'/>%s%s</svg>"
            % (w, h + ch, FONT, w, h + ch, body, cap))


def _wrap(text, width):
    words, lines, cur = str(text).split(), [], ""
    for wd in words:
        trial = (cur + " " + wd).strip()
        if len(trial) > width and cur:
            lines.append(cur)
            cur = wd
        else:
            cur = trial
    if cur:
        lines.append(cur)
    return lines


# ──────────────────────────────────────────────────────────────────────────
# XY line / scatter chart
# ──────────────────────────────────────────────────────────────────────────
def line_chart(series, x_label, y_label, x_range, y_range,
               w=460, h=300, caption=None, x_ticks=None, y_ticks=None,
               markers=True, annotations=None, hlines=None, legend_pos="tr"):
    """series: list of dicts {name, points:[(x,y)...], color?, dashed?}"""
    L, R, T, B = 68, 24, 20, 52
    pw, ph = w - L - R, h - T - B
    x0, x1 = x_range
    y0, y1 = y_range

    def sx(x):
        return L + (x - x0) / float(x1 - x0) * pw

    def sy(y):
        return T + ph - (y - y0) / float(y1 - y0) * ph

    xt = x_ticks if x_ticks is not None else _nice_ticks(x0, x1, 5)
    yt = y_ticks if y_ticks is not None else _nice_ticks(y0, y1, 5)

    p = []
    # gridlines + ticks
    for v in yt:
        p.append("<line x1='%.1f' y1='%.1f' x2='%.1f' y2='%.1f' stroke='%s'/>"
                 % (L, sy(v), L + pw, sy(v), GRID))
        p.append("<text x='%.1f' y='%.1f' font-size='11' fill='#444' text-anchor='end'>%s</text>"
                 % (L - 7, sy(v) + 4, _esc(_n(v))))
    for v in xt:
        p.append("<line x1='%.1f' y1='%.1f' x2='%.1f' y2='%.1f' stroke='#888'/>"
                 % (sx(v), T + ph, sx(v), T + ph + 5))
        p.append("<text x='%.1f' y='%.1f' font-size='11' fill='#444' text-anchor='middle'>%s</text>"
                 % (sx(v), T + ph + 18, _esc(_n(v))))
    # axes
    p.append("<line x1='%.1f' y1='%.1f' x2='%.1f' y2='%.1f' stroke='%s' stroke-width='1.6'/>"
             % (L, T, L, T + ph, INK))
    p.append("<line x1='%.1f' y1='%.1f' x2='%.1f' y2='%.1f' stroke='%s' stroke-width='1.6'/>"
             % (L, T + ph, L + pw, T + ph, INK))
    # reference lines
    for hl in (hlines or []):
        yv, lab = hl[0], hl[1]
        p.append("<line x1='%.1f' y1='%.1f' x2='%.1f' y2='%.1f' stroke='#888' "
                 "stroke-width='1.2' stroke-dasharray='5 4'/>" % (L, sy(yv), L + pw, sy(yv)))
        if lab:
            left = len(hl) > 2 and hl[2] == "left"
            p.append("<text x='%.1f' y='%.1f' font-size='10' fill='#666' text-anchor='%s' "
                     "stroke='#FFFFFF' stroke-width='3' paint-order='stroke'>%s</text>"
                     % (L + 6 if left else L + pw - 4, sy(yv) - 5,
                        "start" if left else "end", _esc(lab)))
    # series
    for i, s in enumerate(series):
        col = s.get("color", SERIES_COLORS[i % len(SERIES_COLORS)])
        pts = " ".join("%.1f,%.1f" % (sx(x), sy(y)) for x, y in s["points"])
        dash = " stroke-dasharray='7 4'" if s.get("dashed") else ""
        p.append("<polyline points='%s' fill='none' stroke='%s' stroke-width='2.4'%s/>"
                 % (pts, col, dash))
        if markers:
            for x, y in s["points"]:
                p.append("<circle cx='%.1f' cy='%.1f' r='3.1' fill='%s'/>" % (sx(x), sy(y), col))
    # legend
    # A legend only earns its space when it distinguishes two or more series.
    if sum(1 for s in series if s.get("name")) >= 2:
        named = [s for s in series if s.get("name")]
        lx = L + 12 if legend_pos == "tl" else L + pw - 168
        ly = T + 4 if legend_pos in ("tl", "tr") else T + ph - 18 * len(named) - 10
        p.append("<rect x='%.1f' y='%.1f' width='164' height='%d' fill='#FFFFFF' "
                 "fill-opacity='0.9' stroke='#E2E2E2' rx='3'/>" % (lx - 6, ly - 2, 18 * len(named) + 6))
        for i, s in enumerate(series):
            if not s.get("name"):
                continue
            col = s.get("color", SERIES_COLORS[i % len(SERIES_COLORS)])
            p.append("<rect x='%.1f' y='%.1f' width='18' height='4' fill='%s' rx='2'/>"
                     % (lx, ly + 5, col))
            p.append("<text x='%.1f' y='%.1f' font-size='11' fill='#333'>%s</text>"
                     % (lx + 24, ly + 10, _esc(s["name"])))
            ly += 18
    # annotations
    for a in (annotations or []):
        ax, ay, txt = a[0], a[1], a[2]
        anchor = a[3] if len(a) > 3 else "middle"
        p.append("<text x='%.1f' y='%.1f' font-size='11' fill='#333' text-anchor='%s'>%s</text>"
                 % (sx(ax), sy(ay), anchor, _esc(txt)))
    # axis titles
    p.append("<text x='%.1f' y='%d' font-size='12' fill='%s' text-anchor='middle'>%s</text>"
             % (L + pw / 2.0, h - 8, INK, _esc(x_label)))
    p.append("<text x='16' y='%.1f' font-size='12' fill='%s' text-anchor='middle' "
             "transform='rotate(-90 16,%.1f)'>%s</text>"
             % (T + ph / 2.0, INK, T + ph / 2.0, _esc(y_label)))
    return _frame(w, h, "".join(p), caption)


# ──────────────────────────────────────────────────────────────────────────
# Vertical bar chart (optionally grouped)
# ──────────────────────────────────────────────────────────────────────────
def bar_chart(categories, groups, y_label, y_max, w=460, h=300,
              caption=None, value_labels=True, y_ticks=None):
    """groups: list of dicts {name, values:[...], color?} parallel to categories."""
    L, R, T, B = 66, 20, 26, 62
    pw, ph = w - L - R, h - T - B

    def sy(v):
        return T + ph - (v / float(y_max)) * ph

    p = []
    for v in (y_ticks if y_ticks is not None else _nice_ticks(0, y_max, 5)):
        p.append("<line x1='%.1f' y1='%.1f' x2='%.1f' y2='%.1f' stroke='%s'/>"
                 % (L, sy(v), L + pw, sy(v), GRID))
        p.append("<text x='%.1f' y='%.1f' font-size='11' fill='#444' text-anchor='end'>%s</text>"
                 % (L - 7, sy(v) + 4, _esc(_n(v))))
    p.append("<line x1='%.1f' y1='%.1f' x2='%.1f' y2='%.1f' stroke='%s' stroke-width='1.6'/>"
             % (L, T, L, T + ph, INK))
    p.append("<line x1='%.1f' y1='%.1f' x2='%.1f' y2='%.1f' stroke='%s' stroke-width='1.6'/>"
             % (L, T + ph, L + pw, T + ph, INK))

    n, g = len(categories), len(groups)
    slot = pw / float(n)
    bw = min(46.0, slot * 0.72 / g)
    for ci, cat in enumerate(categories):
        cx = L + slot * ci + slot / 2.0
        start = cx - (bw * g) / 2.0
        for gi, grp in enumerate(groups):
            v = grp["values"][ci]
            col = grp.get("color", SERIES_COLORS[gi % len(SERIES_COLORS)])
            bx = start + gi * bw
            p.append("<rect x='%.1f' y='%.1f' width='%.1f' height='%.1f' fill='%s' rx='2'/>"
                     % (bx, sy(v), bw - 3, (T + ph) - sy(v), col))
            if value_labels:
                p.append("<text x='%.1f' y='%.1f' font-size='10' fill='#333' "
                         "text-anchor='middle'>%s</text>" % (bx + (bw - 3) / 2.0, sy(v) - 4, _esc(_n(v))))
        for li, ln in enumerate(_wrap(cat, 14)):
            p.append("<text x='%.1f' y='%.1f' font-size='11' fill='#333' text-anchor='middle'>%s</text>"
                     % (cx, T + ph + 17 + li * 12, _esc(ln)))
    if g > 1:
        lx = L
        for gi, grp in enumerate(groups):
            col = grp.get("color", SERIES_COLORS[gi % len(SERIES_COLORS)])
            p.append("<rect x='%.1f' y='6' width='11' height='11' fill='%s' rx='2'/>" % (lx, col))
            p.append("<text x='%.1f' y='15' font-size='11' fill='#333'>%s</text>"
                     % (lx + 15, _esc(grp["name"])))
            lx += 20 + 7.0 * len(grp["name"])
    p.append("<text x='16' y='%.1f' font-size='12' fill='%s' text-anchor='middle' "
             "transform='rotate(-90 16,%.1f)'>%s</text>"
             % (T + ph / 2.0, INK, T + ph / 2.0, _esc(y_label)))
    return _frame(w, h, "".join(p), caption)


# ──────────────────────────────────────────────────────────────────────────
# Data table
# ──────────────────────────────────────────────────────────────────────────
def table(headers, rows, w=470, caption=None, col_w=None, highlight_row=None):
    rh = 26
    n = len(headers)
    widths = col_w or [w / float(n)] * n
    total = sum(widths)
    widths = [x / total * (w - 2) for x in widths]
    max_lines = max(len(_wrap(hd, max(8, int(widths[i] / 6.2)))) for i, hd in enumerate(headers))
    hh = 18 + 12 * max_lines
    h = hh + rh * len(rows) + 2
    p = ["<rect x='1' y='1' width='%.1f' height='%.1f' fill='none' stroke='#BBB'/>" % (w - 2, h - 2)]
    p.append("<rect x='1' y='1' width='%.1f' height='%d' fill='#F2EFE9'/>" % (w - 2, hh))
    x = 1.0
    for i, hd in enumerate(headers):
        lines = _wrap(hd, max(8, int(widths[i] / 6.2)))
        for li, ln in enumerate(lines):
            p.append("<text x='%.1f' y='%.1f' font-size='11' font-weight='bold' fill='%s' "
                     "text-anchor='middle'>%s</text>"
                     % (x + widths[i] / 2.0, hh / 2.0 + 4 - (len(lines) - 1) * 6 + li * 12, INK, _esc(ln)))
        x += widths[i]
        if i < n - 1:
            p.append("<line x1='%.1f' y1='1' x2='%.1f' y2='%.1f' stroke='#DDD'/>" % (x, x, h - 1))
    p.append("<line x1='1' y1='%d' x2='%.1f' y2='%d' stroke='#999' stroke-width='1.4'/>"
             % (hh, w - 1, hh))
    for ri, row in enumerate(rows):
        ry = hh + rh * ri
        if highlight_row == ri:
            p.append("<rect x='1' y='%.1f' width='%.1f' height='%d' fill='#FDF0F2'/>" % (ry, w - 2, rh))
        elif ri % 2:
            p.append("<rect x='1' y='%.1f' width='%.1f' height='%d' fill='#FAFAF8'/>" % (ry, w - 2, rh))
        x = 1.0
        for ci, cell in enumerate(row):
            anchor, tx = ("start", x + 9) if ci == 0 else ("middle", x + widths[ci] / 2.0)
            p.append("<text x='%.1f' y='%.1f' font-size='11.5' fill='#333' text-anchor='%s'>%s</text>"
                     % (tx, ry + rh / 2.0 + 4, anchor, _esc(cell)))
            x += widths[ci]
        if ri:
            p.append("<line x1='1' y1='%.1f' x2='%.1f' y2='%.1f' stroke='#ECECEC'/>" % (ry, w - 1, ry))
    return _frame(w, h, "".join(p), caption)


# ──────────────────────────────────────────────────────────────────────────
# Age-structure pyramid
# ──────────────────────────────────────────────────────────────────────────
def age_pyramid(bands, male, female, w=430, h=300, caption=None, max_pct=None,
                title_left="Male", title_right="Female"):
    L, R, T, B = 10, 10, 30, 46
    cw = 54          # centre label column
    pw, ph = w - L - R - cw, h - T - B
    half = pw / 2.0
    mx = max_pct or (max(max(male), max(female)) * 1.12)
    bh = ph / float(len(bands))
    cx0 = L + half
    cx1 = cx0 + cw
    p = []
    for i, band in enumerate(reversed(bands)):
        idx = len(bands) - 1 - i
        y = T + bh * i
        mwid = male[idx] / mx * half
        fwid = female[idx] / mx * half
        p.append("<rect x='%.1f' y='%.1f' width='%.1f' height='%.1f' fill='#1565C0' rx='1'/>"
                 % (cx0 - mwid, y + 1.5, mwid, bh - 3))
        p.append("<rect x='%.1f' y='%.1f' width='%.1f' height='%.1f' fill='#C41230' rx='1'/>"
                 % (cx1, y + 1.5, fwid, bh - 3))
        p.append("<text x='%.1f' y='%.1f' font-size='10.5' fill='#333' text-anchor='middle'>%s</text>"
                 % (cx0 + cw / 2.0, y + bh / 2.0 + 3.5, _esc(band)))
    p.append("<line x1='%.1f' y1='%.1f' x2='%.1f' y2='%.1f' stroke='%s'/>"
             % (L, T + ph, L + half, T + ph, INK))
    p.append("<line x1='%.1f' y1='%.1f' x2='%.1f' y2='%.1f' stroke='%s'/>"
             % (cx1, T + ph, cx1 + half, T + ph, INK))
    for frac in (0, 0.5, 1.0):
        v = mx * frac
        p.append("<text x='%.1f' y='%.1f' font-size='10' fill='#555' text-anchor='middle'>%s</text>"
                 % (cx0 - half * frac, T + ph + 14, _esc("%g" % round(v, 1))))
        p.append("<text x='%.1f' y='%.1f' font-size='10' fill='#555' text-anchor='middle'>%s</text>"
                 % (cx1 + half * frac, T + ph + 14, _esc("%g" % round(v, 1))))
    p.append("<text x='%.1f' y='18' font-size='12' font-weight='bold' fill='#1565C0' "
             "text-anchor='middle'>%s</text>" % (cx0 - half / 2.0, _esc(title_left)))
    p.append("<text x='%.1f' y='18' font-size='12' font-weight='bold' fill='#C41230' "
             "text-anchor='middle'>%s</text>" % (cx1 + half / 2.0, _esc(title_right)))
    p.append("<text x='%.1f' y='%.1f' font-size='11' fill='#333' text-anchor='middle'>"
             "percent of total population</text>" % (w / 2.0, T + ph + 32))
    p.append("<text x='%.1f' y='%.1f' font-size='10' fill='#555' text-anchor='middle'>age</text>"
             % (cx0 + cw / 2.0, T + ph + 14))
    return _frame(w, h, "".join(p), caption)


# ──────────────────────────────────────────────────────────────────────────
# Box-and-arrow flow diagram (nutrient cycles, energy flow, treatment trains)
# ──────────────────────────────────────────────────────────────────────────
def flow_diagram(boxes, arrows, w=470, h=300, caption=None):
    """boxes: {id,x,y,w,h,label,fill?}; arrows: {frm,to,label?,side?,dashed?}

    Coordinates are top-left of each box in SVG user units.
    `side` picks the attachment: 'auto' (default), 'h' or 'v'.
    """
    byid = {b["id"]: b for b in boxes}
    p = ["<defs><marker id='ah' viewBox='0 0 10 10' refX='9' refY='5' markerWidth='7' "
         "markerHeight='7' orient='auto-start-reverse'>"
         "<path d='M 0 0 L 10 5 L 0 10 z' fill='#555'/></marker></defs>"]

    def centre(b):
        return b["x"] + b["w"] / 2.0, b["y"] + b["h"] / 2.0

    for a in arrows:
        b1, b2 = byid[a["frm"]], byid[a["to"]]
        c1x, c1y = centre(b1)
        c2x, c2y = centre(b2)
        side = a.get("side", "auto")
        if side == "auto":
            side = "h" if abs(c2x - c1x) >= abs(c2y - c1y) else "v"
        if side == "h":
            if c2x >= c1x:
                x1, y1, x2, y2 = b1["x"] + b1["w"], c1y, b2["x"], c2y
            else:
                x1, y1, x2, y2 = b1["x"], c1y, b2["x"] + b2["w"], c2y
        else:
            if c2y >= c1y:
                x1, y1, x2, y2 = c1x, b1["y"] + b1["h"], c2x, b2["y"]
            else:
                x1, y1, x2, y2 = c1x, b1["y"], c2x, b2["y"] + b2["h"]
        dash = " stroke-dasharray='6 4'" if a.get("dashed") else ""
        p.append("<line x1='%.1f' y1='%.1f' x2='%.1f' y2='%.1f' stroke='#555' "
                 "stroke-width='1.8' marker-end='url(#ah)'%s/>" % (x1, y1, x2, y2, dash))
        if a.get("label"):
            mx, my = (x1 + x2) / 2.0, (y1 + y2) / 2.0
            lines = _wrap(a["label"], 18)
            for li, ln in enumerate(lines):
                p.append("<text x='%.1f' y='%.1f' font-size='10.5' fill='#C41230' "
                         "text-anchor='middle' stroke='#FFFFFF' stroke-width='4' "
                         "paint-order='stroke' stroke-linejoin='round'>%s</text>"
                         % (mx, my - 6 - (len(lines) - 1 - li) * 11, _esc(ln)))
    for b in boxes:
        p.append("<rect x='%.1f' y='%.1f' width='%.1f' height='%.1f' fill='%s' stroke='#555' "
                 "stroke-width='1.3' rx='4'/>"
                 % (b["x"], b["y"], b["w"], b["h"], b.get("fill", "#F2EFE9")))
        lines = _wrap(b["label"], max(10, int(b["w"] / 6.3)))
        cy = b["y"] + b["h"] / 2.0 - (len(lines) - 1) * 6
        for li, ln in enumerate(lines):
            p.append("<text x='%.1f' y='%.1f' font-size='11.5' fill='%s' text-anchor='middle'>%s</text>"
                     % (b["x"] + b["w"] / 2.0, cy + 4 + li * 12.5, INK, _esc(ln)))
    return _frame(w, h, "".join(p), caption)


# ──────────────────────────────────────────────────────────────────────────
# Stacked horizontal layer diagram (soil horizons, atmosphere, landfill)
# ──────────────────────────────────────────────────────────────────────────
def layer_diagram(layers, w=450, h=300, caption=None, left_label=None, scale_labels=None):
    """layers: list of {label, thick, fill, note?} drawn top to bottom."""
    L, R, T, B = 96, 150, 16, 16
    pw, ph = w - L - R, h - T - B
    tot = float(sum(l["thick"] for l in layers))
    p, y = [], float(T)
    for l in layers:
        lh = l["thick"] / tot * ph
        p.append("<rect x='%.1f' y='%.1f' width='%.1f' height='%.1f' fill='%s' stroke='#555' "
                 "stroke-width='1'/>" % (L, y, pw, lh, l["fill"]))
        p.append("<text x='%.1f' y='%.1f' font-size='11.5' font-weight='bold' fill='%s' "
                 "text-anchor='end'>%s</text>" % (L - 9, y + lh / 2.0 + 4, INK, _esc(l["label"])))
        if l.get("note"):
            lines = _wrap(l["note"], 24)
            cy = y + lh / 2.0 - (len(lines) - 1) * 6
            for li, ln in enumerate(lines):
                p.append("<text x='%.1f' y='%.1f' font-size='10.5' fill='#444'>%s</text>"
                         % (L + pw + 9, cy + 4 + li * 12, _esc(ln)))
        y += lh
    if left_label:
        p.append("<text x='14' y='%.1f' font-size='12' fill='%s' text-anchor='middle' "
                 "transform='rotate(-90 14,%.1f)'>%s</text>"
                 % (T + ph / 2.0, INK, T + ph / 2.0, _esc(left_label)))
    for sl in (scale_labels or []):
        frac, txt = sl
        p.append("<text x='%.1f' y='%.1f' font-size='10' fill='#666' text-anchor='end'>%s</text>"
                 % (L - 9, T + ph * frac + 4, _esc(txt)))
    return _frame(w, h, "".join(p), caption)


# ──────────────────────────────────────────────────────────────────────────
# Short text source block (Practice 3 items)
# ──────────────────────────────────────────────────────────────────────────
def source_block(title, byline, paragraphs, w=470, caption=None):
    lines_per = [_wrap(t, 72) for t in paragraphs]
    nlines = sum(len(x) for x in lines_per)
    h = 54 + 16 * nlines + 14 * (len(paragraphs) - 1) + 14
    p = ["<rect x='1' y='1' width='%.1f' height='%.1f' fill='#FAFAF8' stroke='#D8D3C8'/>" % (w - 2, h - 2),
         "<rect x='1' y='1' width='5' height='%.1f' fill='#C41230'/>" % (h - 2)]
    p.append("<text x='20' y='26' font-size='13' font-weight='bold' fill='%s'>%s</text>"
             % (INK, _esc(title)))
    p.append("<text x='20' y='43' font-size='10.5' fill='#777' font-style='italic'>%s</text>"
             % _esc(byline))
    y = 64
    for blk in lines_per:
        for ln in blk:
            p.append("<text x='20' y='%.1f' font-size='11.5' fill='#333'>%s</text>" % (y, _esc(ln)))
            y += 16
        y += 14
    return _frame(w, h, "".join(p), caption)


