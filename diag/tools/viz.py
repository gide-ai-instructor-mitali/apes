def sketch(w, h, elements, caption=None):
    """Escape hatch for one-off schematics: `elements` is a list of raw SVG
    fragments already built from computed coordinates."""
    return _frame(w, h, "".join(elements), caption)


def text_el(x, y, s, size=11, fill="#333", anchor="start", weight="normal", italic=False):
    st = " font-style='italic'" if italic else ""
    return ("<text x='%.1f' y='%.1f' font-size='%s' fill='%s' text-anchor='%s' "
            "font-weight='%s'%s>%s</text>" % (x, y, size, fill, anchor, weight, st, _esc(s)))


def rect_el(x, y, w, h, fill, stroke="#555", sw=1.1, rx=2):
    return ("<rect x='%.1f' y='%.1f' width='%.1f' height='%.1f' fill='%s' stroke='%s' "
            "stroke-width='%s' rx='%s'/>" % (x, y, w, h, fill, stroke, sw, rx))


def line_el(x1, y1, x2, y2, stroke="#555", sw=1.4, dash=None, arrow=False):
    d = " stroke-dasharray='%s'" % dash if dash else ""
    a = " marker-end='url(#ah)'" if arrow else ""
    return ("<line x1='%.1f' y1='%.1f' x2='%.1f' y2='%.1f' stroke='%s' stroke-width='%s'%s%s/>"
            % (x1, y1, x2, y2, stroke, sw, d, a))


def path_el(d, fill="none", stroke="#555", sw=1.6, dash=None):
    ds = " stroke-dasharray='%s'" % dash if dash else ""
    return "<path d='%s' fill='%s' stroke='%s' stroke-width='%s'%s/>" % (d, fill, stroke, sw, ds)


def circle_el(cx, cy, r, fill="#C41230", stroke="none", sw=1):
    return ("<circle cx='%.1f' cy='%.1f' r='%.1f' fill='%s' stroke='%s' stroke-width='%s'/>"
            % (cx, cy, r, fill, stroke, sw))


